if __name__ == '__main__':
    poses = {r: P.get(r, b.pose(r)) for r in b.comps}
    out = sys.argv[2]
    _, before = b.ratsnest()
    b.H_new = H
    total = b.draw(out, poses, H=H, title='新布局 50x50')
    hb = b.H; b.H = H; b.holes = [(x, (y if y < hb / 2 else H - (hb - y)), d, v) for x, y, d, v in b.holes]
    print('飞线总长: 原来 %.0f mm -> 现在 %.0f mm' % (before, total)); print('间距问题:', b.overlaps(poses))
    for n, pts in b.nets(poses).items():
        if n in ('ADC1', 'ADC2', 'U3-SW', 'U3-FB', 'VDDA', 'TX+', 'TX-', 'RX+', 'RX-', 'UART_TX', 'UART_RX'):
            L = sum(s[3] for s in b.ratsnest(poses)[0] if s[0] == n); print(f'  {n:8s} {L:5.1f} mm')
    b.H = hb
    if len(sys.argv) > 3:
        b2 = Board(SRC); b2.save(sys.argv[3], poses, H=H); print('已写出', sys.argv[3])
