#include "fatfs.h"

/* 初始化为“尚未注册”，避免静态零初始化被误认为已成功。 */
uint8_t retSD = 1U;
char SDPath[4] = {0};
FATFS SDFatFS;

/* 驱动注册和卷挂载是两个独立过程；这里只记录驱动是否注册成功。
 * 不保留官方演示用的全局 FIL SDFile，文件句柄由第二阶段封装管理。 */
static uint8_t sd_driver_linked = 0U;

void MX_FATFS_Init(void)
{
    if (sd_driver_linked == 0U)
    {
        retSD = FATFS_LinkDriver(&SD_Driver, SDPath);
        if (retSD == 0U)
        {
            sd_driver_linked = 1U;
        }
    }
}

